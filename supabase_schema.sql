create table if not exists public.shared_books (
    id bigint generated by default as identity primary key,
    created_at timestamptz not null default now(),
    isbn text not null default '' check (char_length(isbn) <= 13),
    title text not null check (char_length(btrim(title)) between 1 and 300),
    author text not null check (char_length(btrim(author)) between 1 and 200),
    publisher text not null default '' check (char_length(publisher) <= 200),
    points integer not null check (points between 40 and 180),
    cycles integer not null default 0 check (cycles between 0 and 7),
    condition text not null default '' check (condition in ('', 'excellent', 'good', 'fair', 'damaged')),
    condition_notes text not null default '' check (char_length(condition_notes) <= 500),
    condition_checks jsonb not null default '{}'::jsonb check (jsonb_typeof(condition_checks) = 'object'),
    location text not null check (char_length(btrim(location)) between 1 and 160),
    book_location text not null default '' check (char_length(book_location) <= 200),
    region text not null default '' check (region in ('', 'north', 'central', 'south', 'east', 'islands')),
    language text not null default '' check (language in ('', 'zh', 'en', 'ja', 'other')),
    seller_id text not null check (seller_id ~ '^[A-Za-z0-9_-]{1,80}$'),
    seller_name text not null default '書友' check (char_length(seller_name) <= 80),
    listing_bonus_points integer not null default 0 check (listing_bonus_points between 0 and 50),
    risk_flags jsonb not null default '[]'::jsonb check (jsonb_typeof(risk_flags) = 'array')
);

alter table public.shared_books enable row level security;

drop policy if exists "Anyone can read shared books" on public.shared_books;
create policy "Anyone can read shared books"
    on public.shared_books for select
    to anon, authenticated
    using (true);

drop policy if exists "Anyone can list shared books" on public.shared_books;
create policy "Anyone can list shared books"
    on public.shared_books for insert
    to anon, authenticated
    with check (true);

grant select, insert on public.shared_books to anon, authenticated;
grant usage, select on sequence public.shared_books_id_seq to anon, authenticated;

create table if not exists public.shared_book_transactions (
    order_id text primary key check (order_id ~ '^[A-Za-z0-9_-]{1,100}$'),
    book_id bigint not null references public.shared_books(id),
    buyer_id text not null check (buyer_id ~ '^[A-Za-z0-9_-]{1,80}$'),
    seller_id text not null check (seller_id ~ '^[A-Za-z0-9_-]{1,80}$'),
    book_title text not null check (char_length(btrim(book_title)) between 1 and 300),
    book_author text not null check (char_length(btrim(book_author)) between 1 and 200),
    isbn text not null default '' check (char_length(isbn) <= 13),
    mode text not null check (mode in ('swap', 'points', 'money')),
    amount_points integer not null default 0 check (amount_points between 0 and 180),
    delivery_method text not null check (delivery_method in ('store', 'bookbox')),
    status text not null check (status in (
        'negotiating', 'awaiting_payment', 'awaiting_shipment', 'shipped',
        'cooldown', 'disputed', 'risk_review', 'settled', 'cancelled', 'refunded'
    )),
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    settled_at timestamptz
);

create index if not exists shared_book_transactions_buyer_idx
    on public.shared_book_transactions (buyer_id, created_at desc);
create index if not exists shared_book_transactions_seller_idx
    on public.shared_book_transactions (seller_id, created_at desc);
create unique index if not exists shared_book_one_active_transaction_idx
    on public.shared_book_transactions (book_id)
    where status in (
        'negotiating', 'awaiting_payment', 'awaiting_shipment', 'shipped',
        'cooldown', 'disputed', 'risk_review'
    );

alter table public.shared_book_transactions enable row level security;

